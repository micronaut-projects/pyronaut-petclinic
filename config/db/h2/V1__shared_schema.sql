CREATE ALIAS IF NOT EXISTS H2GIS_SPATIAL FOR 'org.h2gis.functions.factory.H2GISFunctions.load';
CALL H2GIS_SPATIAL();

CREATE TABLE TYPES (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NAME VARCHAR(255) NOT NULL);

CREATE TABLE SPECIALTIES (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NAME VARCHAR(255) NOT NULL);

CREATE TABLE OWNERS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,FIRST_NAME VARCHAR(255) NOT NULL,LAST_NAME VARCHAR(255) NOT NULL,ADDRESS VARCHAR(255) NOT NULL,CITY VARCHAR(255) NOT NULL,TELEPHONE VARCHAR(255));

CREATE TABLE PETS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NAME VARCHAR(255) NOT NULL,BIRTH_DATE DATE NOT NULL,TYPE_ID INT NOT NULL,OWNER_ID INT NOT NULL);

CREATE TABLE VISITS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,VISIT_DATE DATE NOT NULL,DESCRIPTION VARCHAR(255) NOT NULL,PET_ID INT NOT NULL,DURATION VARCHAR(255) NOT NULL,FOLLOW_UP_PERIOD VARCHAR(255) NOT NULL);

CREATE TABLE VETS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,FIRST_NAME VARCHAR(255) NOT NULL,LAST_NAME VARCHAR(255) NOT NULL);

CREATE TABLE VET_SPECIALTIES (VET_ID INT NOT NULL,SPECIALTY_ID INT NOT NULL);

CREATE TABLE CLINICS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NAME VARCHAR(255) NOT NULL,ADDRESS VARCHAR(255) NOT NULL,CITY VARCHAR(255) NOT NULL,ACCEPTING_NEW_PATIENTS BOOLEAN NOT NULL,EMERGENCY_SERVICE BOOLEAN NOT NULL,LOCATION GEOMETRY NOT NULL,SERVICE_AREA GEOMETRY NOT NULL);

CREATE TABLE CLINIC_SERVICE_OFFERINGS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,CLINIC_ID INT NOT NULL,SERVICE_CODE VARCHAR(255) NOT NULL,NAME VARCHAR(255) NOT NULL,DESCRIPTION VARCHAR(255),PRICE DECIMAL(10, 2) NOT NULL,DURATION_MINUTES INT NOT NULL);

CREATE TABLE APPOINTMENTS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,LABEL VARCHAR(255) NOT NULL,DISPLAY_ORDER INT NOT NULL,STATUS VARCHAR(255) NOT NULL);

CREATE TABLE PET_CARE_DOCUMENTS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,TITLE VARCHAR(255) NOT NULL,SOURCE VARCHAR(255) NOT NULL,DESCRIPTION VARCHAR(255) NOT NULL);

CREATE TABLE PET_CARE_CHUNKS (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,DOCUMENT_ID INT NOT NULL,DOCUMENT_TITLE VARCHAR(255) NOT NULL,DOCUMENT_SOURCE VARCHAR(255) NOT NULL,TOPIC VARCHAR(255) NOT NULL,SPECIES VARCHAR(255) NOT NULL,CHUNK_INDEX INT NOT NULL,CONTENT VARCHAR(255) NOT NULL,EMBEDDING VARCHAR(255) NOT NULL);

ALTER TABLE CLINIC_SERVICE_OFFERINGS ADD CONSTRAINT UK_CLINIC_SERVICE_CODE UNIQUE (CLINIC_ID, SERVICE_CODE);

CREATE SPATIAL INDEX IDX_CLINICS_LOCATION ON CLINICS (LOCATION);
CREATE SPATIAL INDEX IDX_CLINICS_SERVICE_AREA ON CLINICS (SERVICE_AREA);
