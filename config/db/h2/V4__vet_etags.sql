-- Keep this signature aligned with Vet's generated ETag inputs.
CREATE ALIAS IF NOT EXISTS SYS_ROW_ETAG FOR 'petclinic.VetEtagFunctions.sysRowEtag';
ALTER TABLE VETS ADD SPECIALITIES_ETAG_HASH VARCHAR(64) DEFAULT 'E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855' NOT NULL;
UPDATE VETS v SET SPECIALITIES_ETAG_HASH = (
    SELECT UPPER(RAWTOHEX(HASH('SHA-256', STRINGTOUTF8(COALESCE(
        LISTAGG(CAST(vs.SPECIALTY_ID AS VARCHAR), ',') WITHIN GROUP (ORDER BY vs.SPECIALTY_ID), '')))))
    FROM VET_SPECIALTIES vs WHERE vs.VET_ID = v.id);
