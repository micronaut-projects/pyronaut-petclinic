-- Native generated ETags use id, first name, last name and assignment hash.
ALTER TABLE VETS ADD SPECIALITIES_ETAG_HASH VARCHAR(64) DEFAULT 'E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855' NOT NULL;

UPDATE VETS v LEFT JOIN (
    SELECT VET_ID, UPPER(SHA2(GROUP_CONCAT(CAST(SPECIALTY_ID AS CHAR) ORDER BY SPECIALTY_ID SEPARATOR ','), 256)) AS assignment_hash
    FROM VET_SPECIALTIES GROUP BY VET_ID
) links ON links.VET_ID = v.id SET v.SPECIALITIES_ETAG_HASH = COALESCE(links.assignment_hash, 'E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855');

DROP FUNCTION IF EXISTS SYS_ROW_ETAG;
CREATE FUNCTION SYS_ROW_ETAG(
    vet_id INT,
    first_name VARCHAR(255),
    last_name VARCHAR(255),
    specialities_hash VARCHAR(64)
)
RETURNS CHAR(32) CHARACTER SET ascii
DETERMINISTIC
RETURN UPPER(LEFT(SHA2(CONCAT(
    IF(vet_id IS NULL, '-1:', CONCAT(CHAR_LENGTH(CAST(vet_id AS CHAR)), ':', CAST(vet_id AS CHAR))),
    IF(first_name IS NULL, '-1:', CONCAT(CHAR_LENGTH(first_name), ':', first_name)),
    IF(last_name IS NULL, '-1:', CONCAT(CHAR_LENGTH(last_name), ':', last_name)),
    IF(specialities_hash IS NULL, '-1:', CONCAT(CHAR_LENGTH(specialities_hash), ':', specialities_hash))
), 256), 32));
