CREATE TABLE PET_TYPES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL UNIQUE
);

CREATE TABLE SPECIALITIES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL UNIQUE
);

CREATE TABLE OWNERS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(30) NOT NULL,
    LAST_NAME VARCHAR2(30) NOT NULL,
    ADDRESS VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(80) NOT NULL,
    TELEPHONE VARCHAR2(20) NOT NULL
);

CREATE TABLE PETS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(30) NOT NULL,
    BIRTH_DATE DATE NOT NULL,
    TYPE_ID NUMBER(19) NOT NULL REFERENCES PET_TYPES (ID),
    OWNER_ID NUMBER(19) NOT NULL REFERENCES OWNERS (ID)
);

CREATE TABLE VISITS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VISIT_DATE DATE NOT NULL,
    DESCRIPTION VARCHAR2(255) NOT NULL,
    PET_ID NUMBER(19) NOT NULL REFERENCES PETS (ID)
);

CREATE TABLE VETS (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FIRST_NAME VARCHAR2(30) NOT NULL,
    LAST_NAME VARCHAR2(30) NOT NULL
);

CREATE TABLE VET_SPECIALITIES (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VET_ID NUMBER(19) NOT NULL REFERENCES VETS (ID),
    SPECIALITY_ID NUMBER(19) NOT NULL REFERENCES SPECIALITIES (ID),
    CONSTRAINT UK_VET_SPECIALITY UNIQUE (VET_ID, SPECIALITY_ID)
);

CREATE INDEX IDX_PETS_OWNER ON PETS (OWNER_ID);
CREATE INDEX IDX_VISITS_PET ON VISITS (PET_ID);
