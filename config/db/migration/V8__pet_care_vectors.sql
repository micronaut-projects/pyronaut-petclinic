CREATE SEQUENCE PET_CARE_DOCUMENTS_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE PET_CARE_CHUNKS_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE PET_CARE_DOCUMENTS (
    ID NUMBER(10) NOT NULL PRIMARY KEY,
    TITLE VARCHAR2(255) NOT NULL,
    SOURCE VARCHAR2(255) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL
);

CREATE TABLE PET_CARE_CHUNKS (
    ID NUMBER(10) NOT NULL PRIMARY KEY,
    DOCUMENT_ID NUMBER(10) NOT NULL REFERENCES PET_CARE_DOCUMENTS(ID),
    DOCUMENT_TITLE VARCHAR2(255) NOT NULL,
    DOCUMENT_SOURCE VARCHAR2(255) NOT NULL,
    TOPIC VARCHAR2(255) NOT NULL,
    SPECIES VARCHAR2(255) NOT NULL,
    CHUNK_INDEX NUMBER(10) NOT NULL,
    CONTENT VARCHAR2(4000) NOT NULL,
    EMBEDDING VECTOR(384, FLOAT32) NOT NULL
);
