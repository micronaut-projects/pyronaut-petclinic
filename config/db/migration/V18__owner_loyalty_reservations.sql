CREATE SEQUENCE OWNER_LOYALTY_ACCOUNT_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE OWNER_LOYALTY_ACCOUNT (
    ID NUMBER(19) NOT NULL PRIMARY KEY,
    OWNER_ID NUMBER(10) NOT NULL,
    POINTS NUMBER(19) RESERVABLE CONSTRAINT CK_OWNER_LOYALTY_POINTS_NONNEGATIVE CHECK (POINTS >= 0) NOT NULL,
    CONSTRAINT FK_OWNER_LOYALTY_OWNER FOREIGN KEY (OWNER_ID) REFERENCES OWNERS(ID)
);
CREATE UNIQUE INDEX UK_OWNER_LOYALTY_ACCOUNT_OWNER ON OWNER_LOYALTY_ACCOUNT (OWNER_ID);

CREATE SEQUENCE OWNER_REWARD_VOUCHERS_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE OWNER_REWARD_VOUCHERS (
    ID NUMBER(19) NOT NULL PRIMARY KEY,
    OWNER_LOYALTY_ACCOUNT_ID NUMBER(19) NOT NULL,
    REWARD_CODE VARCHAR2(255) NOT NULL,
    POINTS_SPENT NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_OWNER_VOUCHER_ACCOUNT FOREIGN KEY (OWNER_LOYALTY_ACCOUNT_ID) REFERENCES OWNER_LOYALTY_ACCOUNT(ID)
);
