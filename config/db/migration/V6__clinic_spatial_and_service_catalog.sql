CREATE SEQUENCE CLINICS_SEQ START WITH 1 INCREMENT BY 1 CACHE 100 NOCYCLE;
CREATE SEQUENCE CLINIC_SERVICE_OFFERINGS_SEQ START WITH 1 INCREMENT BY 1 CACHE 100 NOCYCLE;

CREATE TABLE CLINICS (
    ID NUMBER(19) PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    ADDRESS VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(80) NOT NULL,
    ACCEPTING_NEW_PATIENTS BOOLEAN NOT NULL,
    EMERGENCY_SERVICE BOOLEAN NOT NULL,
    LOCATION MDSYS.SDO_GEOMETRY NOT NULL,
    SERVICE_AREA MDSYS.SDO_GEOMETRY NOT NULL
);

CREATE TABLE CLINIC_SERVICE_OFFERINGS (
    ID NUMBER(19) PRIMARY KEY,
    CLINIC_ID NUMBER(19) NOT NULL REFERENCES CLINICS (ID),
    SERVICE_CODE VARCHAR2(40) NOT NULL,
    NAME VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(500),
    PRICE NUMBER(10, 2) NOT NULL CHECK (PRICE >= 0),
    DURATION_MINUTES NUMBER(10) NOT NULL CHECK (DURATION_MINUTES >= 1),
    CONSTRAINT UK_CLINIC_SERVICE_CODE UNIQUE (CLINIC_ID, SERVICE_CODE)
);

